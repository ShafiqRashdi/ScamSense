#!/usr/bin/env bash
#
# ScamSense — one-time setup of a fresh Ubuntu 24.04 VM (Azure).
#
# Run it as the VM's admin user, with sudo:
#
#     sudo bash setup.sh
#
# or, to skip the two questions:
#
#     sudo DOMAIN=scamsense.malaysiawest.cloudapp.azure.com \
#          ADMIN_EMAIL=you@example.com bash setup.sh
#
# Safe to re-run. Every step checks before it changes anything, and the
# secrets generated on the first run are kept in /etc/scamsense/secrets.env
# and reused, so a second run never rotates a password out from under MySQL.
#
# What it builds (docs/deployment-azure.md, ADR 0013):
#
#   internet ──443──► Caddy (TLS) ──► PHP-FPM ──► Laravel
#                                                   │
#                                   127.0.0.1:5001  ├──► Flask ML service
#                                   127.0.0.1:3306  └──► MySQL 8
#
# Only 22, 80 and 443 are open. The ML service and MySQL listen on loopback,
# so nothing outside this machine can reach them (AGENTS.md §2 rule 1).

set -euo pipefail

REPO_SSH="git@github.com:ShafiqRashdi/ScamSense.git"
APP_DIR="/var/www/scamsense"
CONF_DIR="/etc/scamsense"
SECRETS="$CONF_DIR/secrets.env"
ML_USER="scamsense-ml"
# GitHub's published ed25519 host key fingerprint. Checked before the first
# connection so the clone cannot be pointed at an impostor.
GITHUB_ED25519_FP="SHA256:+DiY3wvvV6TuJJhbpZisF/zLDA0zPMSvHdkr4UvCOqU"

step() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
die() { printf '\n\033[31mSTOP: %s\033[0m\n' "$*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || die "Run with sudo: sudo bash setup.sh"
OWNER="${SUDO_USER:-}"
[[ -n "$OWNER" && "$OWNER" != "root" ]] ||
    die "Run as your admin user with sudo, not as root directly."
OWNER_HOME="$(getent passwd "$OWNER" | cut -d: -f6)"
as_owner() { sudo -u "$OWNER" -H "$@"; }

# ── Settings and secrets ─────────────────────────────────────────────────────
step "Settings and secrets"
install -d -m 700 "$CONF_DIR"
DOMAIN_IN="${DOMAIN:-}"
ADMIN_EMAIL_IN="${ADMIN_EMAIL:-}"
# shellcheck disable=SC1090
[[ -f "$SECRETS" ]] && source "$SECRETS"
DOMAIN="${DOMAIN_IN:-${DOMAIN:-}}"
ADMIN_EMAIL="${ADMIN_EMAIL_IN:-${ADMIN_EMAIL:-}}"

if [[ -z "$DOMAIN" ]]; then
    read -rp "Public address (e.g. scamsense.malaysiawest.cloudapp.azure.com): " DOMAIN
fi
if [[ -z "$ADMIN_EMAIL" ]]; then
    read -rp "Administrator email address: " ADMIN_EMAIL
fi
[[ "$DOMAIN" =~ ^[a-z0-9.-]+$ ]] || die "That address does not look like a hostname: $DOMAIN"
[[ "$ADMIN_EMAIL" == *@* ]] || die "That does not look like an email address: $ADMIN_EMAIL"

gen() { openssl rand -hex 32; }
DB_APP_PASSWORD="${DB_APP_PASSWORD:-$(gen)}"
DB_MIGRATE_PASSWORD="${DB_MIGRATE_PASSWORD:-$(gen)}"
ML_SERVICE_SECRET="${ML_SERVICE_SECRET:-$(gen)}"

(
    umask 077
    cat > "$SECRETS" <<EOF
# Generated by deploy/azure/setup.sh. Root-only. Never copy into the repository.
DOMAIN='$DOMAIN'
ADMIN_EMAIL='$ADMIN_EMAIL'
DB_APP_PASSWORD='$DB_APP_PASSWORD'
DB_MIGRATE_PASSWORD='$DB_MIGRATE_PASSWORD'
ML_SERVICE_SECRET='$ML_SERVICE_SECRET'
EOF
)
echo "Saved to $SECRETS (readable by root only)."

# ── Swap ─────────────────────────────────────────────────────────────────────
# npm, composer and MySQL together can spike past physical RAM during a build.
step "Swap file (2 GB)"
if ! swapon --show | grep -q '^/swapfile'; then
    fallocate -l 2G /swapfile
    chmod 600 /swapfile
    mkswap /swapfile >/dev/null
    swapon /swapfile
    grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi
swapon --show

# ── Packages ─────────────────────────────────────────────────────────────────
# PHP 8.4: composer.lock pins Symfony 8.1, which requires PHP >= 8.4.1, and
#   Ubuntu 24.04 ships 8.3. ondrej/php is the standard source for newer PHP.
# Python 3.11: requirements.txt is pinned and tested on 3.11 (AGENTS.md §5).
# Node 22: Vite 8 needs Node >= 20.19; Ubuntu 24.04 ships 18.
step "System packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -y -q software-properties-common ca-certificates curl gnupg \
    git unzip ufw openssl
add-apt-repository -y ppa:ondrej/php >/dev/null
add-apt-repository -y ppa:deadsnakes/ppa >/dev/null
if ! command -v node >/dev/null || ! node -v | grep -q '^v22\.'; then
    curl -fsSL https://deb.nodesource.com/setup_22.x | bash - >/dev/null
fi
apt-get update -q
apt-get install -y -q \
    php8.4-fpm php8.4-cli php8.4-mysql php8.4-mbstring php8.4-xml \
    php8.4-curl php8.4-zip php8.4-intl php8.4-bcmath \
    mysql-server caddy nodejs python3.11 python3.11-venv
update-alternatives --set php /usr/bin/php8.4 >/dev/null

if ! command -v composer >/dev/null; then
    # The official installer, verified against its published checksum.
    expected="$(curl -fsSL https://composer.github.io/installer.sig)"
    curl -fsSL https://getcomposer.org/installer -o /tmp/composer-setup.php
    actual="$(php -r "echo hash_file('sha384', '/tmp/composer-setup.php');")"
    [[ "$expected" == "$actual" ]] || die "Composer installer checksum mismatch."
    php /tmp/composer-setup.php --install-dir=/usr/local/bin --filename=composer --quiet
    rm -f /tmp/composer-setup.php
fi
php -v | head -1
node -v
python3.11 --version
composer --version

# ── Firewall ─────────────────────────────────────────────────────────────────
# A second layer behind Azure's network security group. 5001 and 3306 are
# never opened here; they are also bound to loopback, so this is belt and
# braces rather than the only thing keeping them private.
step "Firewall: SSH, HTTP, HTTPS only"
ufw allow OpenSSH >/dev/null
ufw allow 80/tcp >/dev/null
ufw allow 443/tcp >/dev/null
ufw --force enable >/dev/null
ufw status

# ── MySQL ────────────────────────────────────────────────────────────────────
# Two users, as in docs/deployment.md §1: the running application cannot
# DROP or ALTER anything (security review finding 7); migrations use a
# separate user only for the duration of the migration.
step "MySQL: database and two scoped users"
systemctl enable --now mysql >/dev/null
mysql <<SQL
CREATE DATABASE IF NOT EXISTS scamsense
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS 'scamsense_app'@'localhost' IDENTIFIED BY '$DB_APP_PASSWORD';
ALTER USER 'scamsense_app'@'localhost' IDENTIFIED BY '$DB_APP_PASSWORD';
GRANT SELECT, INSERT, UPDATE, DELETE ON scamsense.* TO 'scamsense_app'@'localhost';

CREATE USER IF NOT EXISTS 'scamsense_migrate'@'localhost' IDENTIFIED BY '$DB_MIGRATE_PASSWORD';
ALTER USER 'scamsense_migrate'@'localhost' IDENTIFIED BY '$DB_MIGRATE_PASSWORD';
GRANT ALL PRIVILEGES ON scamsense.* TO 'scamsense_migrate'@'localhost';

FLUSH PRIVILEGES;
SQL
echo "MySQL is listening on:"
ss -ltn '( sport = :3306 )' | tail -n +2

# ── Repository ───────────────────────────────────────────────────────────────
# A read-only deploy key: this machine can fetch the private repository and
# can never push to it.
step "Repository access (read-only deploy key)"
KEY="$OWNER_HOME/.ssh/scamsense_deploy"
as_owner install -d -m 700 "$OWNER_HOME/.ssh"
if [[ ! -f "$KEY" ]]; then
    as_owner ssh-keygen -q -t ed25519 -N "" -C "scamsense-deploy@$(hostname)" -f "$KEY"
fi
if ! grep -q 'scamsense_deploy' "$OWNER_HOME/.ssh/config" 2>/dev/null; then
    as_owner tee -a "$OWNER_HOME/.ssh/config" >/dev/null <<EOF

Host github.com
    IdentityFile $KEY
    IdentitiesOnly yes
EOF
    chmod 600 "$OWNER_HOME/.ssh/config"
fi
if ! as_owner ssh-keygen -F github.com >/dev/null 2>&1; then
    scanned="$(ssh-keyscan -t ed25519 github.com 2>/dev/null)"
    fp="$(ssh-keygen -lf - <<<"$scanned" | awk '{print $2}')"
    [[ "$fp" == "$GITHUB_ED25519_FP" ]] ||
        die "GitHub's host key fingerprint is $fp, expected $GITHUB_ED25519_FP. Not continuing."
    echo "$scanned" | as_owner tee -a "$OWNER_HOME/.ssh/known_hosts" >/dev/null
fi

if [[ ! -d "$APP_DIR/.git" ]]; then
    if ! as_owner git ls-remote "$REPO_SSH" >/dev/null 2>&1; then
        cat <<EOF

GitHub does not know this server yet. Add this key to the repository:

  github.com/ShafiqRashdi/ScamSense → Settings → Deploy keys → Add deploy key
  Title: azure-vm      "Allow write access": leave it OFF

$(cat "$KEY.pub")

Then run this script again. Everything done so far is kept.
EOF
        exit 2
    fi
    install -d -o "$OWNER" -g "$OWNER" "$APP_DIR"
    as_owner git clone -q "$REPO_SSH" "$APP_DIR"
fi
echo "Repository at $APP_DIR ($(as_owner git -C "$APP_DIR" log --oneline -1))"

# ── Laravel environment ──────────────────────────────────────────────────────
# Written once. Edit later with `sudo nano $APP_DIR/backend/.env`, then run
# deploy/azure/update.sh so the configuration cache picks up the change.
step "Laravel .env"
ENV_FILE="$APP_DIR/backend/.env"
if [[ ! -f "$ENV_FILE" ]]; then
    APP_KEY="base64:$(openssl rand -base64 32)"
    (
        umask 027
        cat > "$ENV_FILE" <<EOF
APP_NAME=ScamSense
APP_ENV=production
APP_KEY=$APP_KEY
APP_DEBUG=false
APP_URL=https://$DOMAIN

APP_LOCALE=en
APP_FALLBACK_LOCALE=en
APP_FAKER_LOCALE=en_US
APP_MAINTENANCE_DRIVER=file
BCRYPT_ROUNDS=12

LOG_CHANNEL=stack
LOG_STACK=daily
LOG_DAILY_DAYS=14
LOG_LEVEL=info
LOG_DEPRECATIONS_CHANNEL=null

DB_CONNECTION=mysql
DB_HOST=127.0.0.1
DB_PORT=3306
DB_DATABASE=scamsense
DB_USERNAME=scamsense_app
DB_PASSWORD=$DB_APP_PASSWORD

SESSION_DRIVER=database
SESSION_LIFETIME=120
SESSION_ENCRYPT=false
SESSION_PATH=/
SESSION_DOMAIN=null
SESSION_SECURE_COOKIE=true
SESSION_SAME_SITE=lax

BROADCAST_CONNECTION=log
FILESYSTEM_DISK=local
QUEUE_CONNECTION=database
CACHE_STORE=database

MAIL_MAILER=log
MAIL_FROM_ADDRESS="noreply@scamsense.local"
MAIL_FROM_NAME="\${APP_NAME}"

ML_SERVICE_URL=http://127.0.0.1:5001
ML_SERVICE_SECRET=$ML_SERVICE_SECRET

# Optional. Empty means those checks are skipped and the verdict says so.
GOOGLE_SAFE_BROWSING_KEY=
VIRUSTOTAL_KEY=

ADMIN_NAME="ScamSense Administrator"
ADMIN_EMAIL=$ADMIN_EMAIL
# Deliberately empty. Set the password with:
#   sudo -u www-data php artisan scamsense:admin-password
ADMIN_PASSWORD=

RETENTION_SUBMISSION_DAYS=90

VITE_APP_NAME="\${APP_NAME}"
EOF
    )
    echo "Written."
else
    echo "Already exists; left unchanged."
fi
chown "$OWNER:www-data" "$ENV_FILE"
chmod 640 "$ENV_FILE"
usermod -aG www-data "$OWNER"

# ── PHP-FPM ──────────────────────────────────────────────────────────────────
step "PHP-FPM settings"
cat > /etc/php/8.4/fpm/conf.d/99-scamsense.ini <<'EOF'
; ScamSense production settings
expose_php = Off
display_errors = Off
log_errors = On
memory_limit = 256M
opcache.enable = 1
opcache.validate_timestamps = 1
EOF
systemctl enable php8.4-fpm >/dev/null

# ── ML service ───────────────────────────────────────────────────────────────
# Its own system user with no shell and no home, loopback only, one worker
# (the HMAC nonce cache is per-process: docs/deployment.md §2).
step "ML service (systemd, loopback only)"
id "$ML_USER" >/dev/null 2>&1 ||
    useradd --system --no-create-home --shell /usr/sbin/nologin "$ML_USER"
(
    umask 077
    cat > "$CONF_DIR/ml.env" <<EOF
ML_SERVICE_SECRET=$ML_SERVICE_SECRET
PYTHONDONTWRITEBYTECODE=1
EOF
)
cat > /etc/systemd/system/scamsense-ml.service <<EOF
[Unit]
Description=ScamSense ML service (loopback only, never public)
After=network.target

[Service]
User=$ML_USER
Group=$ML_USER
WorkingDirectory=$APP_DIR/ml-service
EnvironmentFile=$CONF_DIR/ml.env
ExecStart=$APP_DIR/ml-service/.venv/bin/gunicorn --bind 127.0.0.1:5001 --workers 1 --timeout 30 wsgi:app
Restart=on-failure
RestartSec=3
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ProtectKernelTunables=true
ProtectControlGroups=true
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable scamsense-ml >/dev/null

# ── Caddy (HTTPS) ────────────────────────────────────────────────────────────
# Caddy obtains and renews a Let's Encrypt certificate for $DOMAIN by itself,
# as long as ports 80 and 443 are open in Azure. No access log: it would
# record every visitor's IP address for no purpose this project has.
step "Caddy web server with automatic HTTPS"
cat > /etc/caddy/Caddyfile <<EOF
$DOMAIN {
	root * $APP_DIR/backend/public
	encode zstd gzip
	php_fastcgi unix//run/php/php8.4-fpm.sock
	file_server
	header -Server
}
EOF
usermod -aG www-data caddy
systemctl enable caddy >/dev/null

# ── Retention purge ──────────────────────────────────────────────────────────
# Once a day, directly. The scheduler has one job, so booting Laravel every
# minute to ask whether it is due would be waste (docs/deployment.md §5).
step "Daily retention purge (03:15 UTC)"
cat > /etc/cron.d/scamsense <<EOF
# ScamSense: delete submissions past RETENTION_SUBMISSION_DAYS (PDPA 2010).
15 3 * * * www-data cd $APP_DIR/backend && /usr/bin/php artisan scamsense:purge --no-interaction >> $APP_DIR/backend/storage/logs/purge.log 2>&1
EOF
chmod 644 /etc/cron.d/scamsense

# ── Build, migrate, start ────────────────────────────────────────────────────
step "Build and start (deploy/azure/update.sh)"
bash "$APP_DIR/deploy/azure/update.sh" --no-pull

# ── Administrator account ────────────────────────────────────────────────────
# The seeder only ever creates. It gets a random password nobody sees; the
# real one is set afterwards with the interactive command, which never prints
# it (docs/deployment.md §4).
step "Administrator account"
cd "$APP_DIR/backend"
# The configuration cache must be cleared first: with it in place Laravel
# ignores environment variables, the seeder sees no ADMIN_PASSWORD, and it
# generates one and PRINTS it (which happened on the first real run).
sudo -u www-data php artisan config:clear
sudo -u www-data env ADMIN_PASSWORD="$(openssl rand -hex 24)" \
    php artisan db:seed --class=AdminUserSeeder --force --no-interaction
sudo -u www-data php artisan config:cache

cat <<EOF

────────────────────────────────────────────────────────────────────────────
Setup finished. Two things left, both yours:

1. Set the administrator password (typed, never shown or logged):

     cd $APP_DIR/backend && sudo -u www-data php artisan scamsense:admin-password

2. Optional: add the threat-intelligence keys, then apply them:

     sudo nano $APP_DIR/backend/.env        # GOOGLE_SAFE_BROWSING_KEY, VIRUSTOTAL_KEY
     sudo bash $APP_DIR/deploy/azure/update.sh --no-pull

Then open https://$DOMAIN
────────────────────────────────────────────────────────────────────────────
EOF
